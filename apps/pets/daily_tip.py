def get_daily_tip(pet=None):
    today    = date.today()
    pet_name = getattr(pet, 'name', '') if pet else ''
    pet_type = getattr(pet, 'pet_type', '').lower() if pet else ''
    pet_id   = getattr(pet, 'id', 0) if pet else 0

    pool = TIPS.get(pet_type, []) + TIPS_GENERAL

    # Seed = วันที่ + pet_id → tip เดิมทั้งวัน เปลี่ยนทุกวัน
    rng = random.Random(today.toordinal() + pet_id)
    tip = rng.choice(pool)

    return tip.replace("{name}", f" {pet_name}" if pet_name else "")